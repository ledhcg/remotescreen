/// The Mac pasteboard, as little as the bridge needs. The real one is `SystemPasteboard`; tests use a fake and never touch
/// the user's clipboard.
public protocol HelperPasteboard: Sendable {
    var changeCount: Int { get }
    /// Type identifiers present on the pasteboard (UTIs, as written by the source application).
    func availableTypes() -> [String]
    func data(for type: String) -> Data?
    /// Names (last path components) of file URLs on the pasteboard. Never full paths.
    func fileNames() -> [String]
    /// Replaces the pasteboard content and returns the new change count.
    func write(_ items: [(type: String, data: Data)]) -> Int
}

public protocol ImageTranscoder: Sendable {
    /// PNG for TIFF data, or nil when it is not a sane image (decode limits are enforced by the implementation).
    func pngData(fromTIFF data: Data) -> Data?
}

/// Wire type identifiers of the clipboard messages and the pasteboard types they map to.
public enum ClipboardWireType {
    public static let text = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let png = "public.png"
    /// Names of copied files, newline separated. A reference only: the content is never sent this way.
    public static let fileReferences = "public.file-url"

    /// In order of preference.
    public static let allowList: [String] = [text, rtf, html, png, fileReferences]

    /// Pasteboard types that carry each wire type.
    static let nativeTypes: [String: [String]] = [
        text: ["public.utf8-plain-text", "NSStringPboardType"],
        rtf: ["public.rtf"],
        html: ["public.html"],
        png: ["public.png", "public.tiff"],
    ]

    /// Markers from nspasteboard.org that password managers and other apps attach to content that must not be synced.
    /// Same list as `ClipboardBridge` on the iPad.
    public static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
}

/// Clipboard sync for the helper (design §4.9). Content moves only on request (`offer` when the client focuses a window or
/// is about to paste); there is no polling. Sensitive content is never offered or sent. Everything received is checked
/// against the allow-list, the size caps and the type's own format before it touches the pasteboard.
public actor PasteboardBridge {
    public static let maxFileReferences = 64

    private let pasteboard: any HelperPasteboard
    private let transcoder: any ImageTranscoder
    private let log = Logger(subsystem: "app.screon.helper", category: "clipboard")

    private var offeredChangeCount: Int?
    private var offeredTypes: Set<String> = []
    /// The change count produced by our own write: not offered back to the client.
    private var ownWriteChangeCount: Int?
    private var requestedType: String?

    public init(pasteboard: any HelperPasteboard, transcoder: any ImageTranscoder) {
        self.pasteboard = pasteboard; self.transcoder = transcoder
    }

    /// Routes a clipboard message. Returns the messages to send back (possibly none).
    public func handle(_ message: LinkMessage) -> [LinkMessage] {
        switch message {
        case .clipboardOffer(let types):
            if let reply = receiveOffer(types) { return [reply] }
            return []
        case .clipboardRequest(let type):
            if let reply = serve(type: type) { return [reply] }
            return []
        case .clipboardData(let type, let data):
            receive(type: type, data: data)
            return []
        default:
            return []
        }
    }

    // MARK: Mac → iPad

    /// Call when the client focuses a window or before it pastes. Returns an offer when the pasteboard changed since the last
    /// one and holds something that may be shared; nil otherwise (unchanged, our own write, sensitive, nothing allowed).
    public func offer() -> LinkMessage? {
        let count = pasteboard.changeCount
        guard count != offeredChangeCount, count != ownWriteChangeCount else { return nil }
        offeredChangeCount = count
        offeredTypes = []
        let types = pasteboard.availableTypes()
        guard !Self.containsSensitive(types) else { return nil }
        let available = wireTypes(for: types)
        guard !available.isEmpty else { return nil }
        offeredTypes = Set(available)
        return .clipboardOffer(types: available)
    }

    /// Answers `clipboard.request`. Nil when the type was not offered, the pasteboard changed since the offer (the client must
    /// ask for a fresh offer rather than get content it was not shown), the content became sensitive, or it is too large.
    public func serve(type: String) -> LinkMessage? {
        guard offeredTypes.contains(type), pasteboard.changeCount == offeredChangeCount else { return nil }
        guard !Self.containsSensitive(pasteboard.availableTypes()) else { return nil }
        guard let data = payload(for: type), data.count <= LinkLimits.maxClipboardBytes else { return nil }
        return .clipboardData(type: type, data: data)
    }

    private func wireTypes(for native: [String]) -> [String] {
        let present = Set(native)
        var result: [String] = []
        for wire in ClipboardWireType.allowList {
            if wire == ClipboardWireType.fileReferences {
                if present.contains("public.file-url"), !pasteboard.fileNames().isEmpty { result.append(wire) }
            } else if let candidates = ClipboardWireType.nativeTypes[wire], candidates.contains(where: present.contains) {
                result.append(wire)
            }
            if result.count >= LinkLimits.maxClipboardTypes { break }
        }
        return result
    }

    private func payload(for wire: String) -> Data? {
        switch wire {
        case ClipboardWireType.fileReferences:
            let names = pasteboard.fileNames().filter(LinkFileName.isValid).prefix(Self.maxFileReferences)
            guard !names.isEmpty else { return nil }
            return Data(names.joined(separator: "\n").utf8)
        case ClipboardWireType.png:
            if let png = pasteboard.data(for: "public.png"), Self.isPNG(png) { return png }
            guard let tiff = pasteboard.data(for: "public.tiff"), tiff.count <= LinkLimits.maxClipboardBytes else { return nil }
            return transcoder.pngData(fromTIFF: tiff)
        default:
            guard let natives = ClipboardWireType.nativeTypes[wire] else { return nil }
            for native in natives { if let data = pasteboard.data(for: native) { return data } }
            return nil
        }
    }

    // MARK: iPad → Mac

    /// Handles the client's offer: asks for the most useful allowed type, or nothing. File references are never requested.
    public func receiveOffer(_ types: [String]) -> LinkMessage? {
        guard types.count <= LinkLimits.maxClipboardTypes else { return nil }
        let offered = Set(types)
        let wanted = [ClipboardWireType.text, ClipboardWireType.rtf, ClipboardWireType.html, ClipboardWireType.png]
        guard let choice = wanted.first(where: offered.contains) else { requestedType = nil; return nil }
        requestedType = choice
        return .clipboardRequest(type: choice)
    }

    /// Accepts the data we asked for, if it is what it claims to be, and writes it to the pasteboard.
    public func receive(type: String, data: Data) {
        guard let requestedType, type == requestedType else { return }
        self.requestedType = nil // one answer per request
        guard data.count <= LinkLimits.maxClipboardBytes, !data.isEmpty else { return }
        switch type {
        case ClipboardWireType.text:
            guard String(data: data, encoding: .utf8) != nil else { return }
        case ClipboardWireType.png:
            guard Self.isPNG(data) else { return }
        case ClipboardWireType.rtf:
            guard data.starts(with: Data("{\\rtf".utf8)) else { return }
        case ClipboardWireType.html:
            guard String(data: data, encoding: .utf8) != nil else { return }
        default:
            return
        }
        ownWriteChangeCount = pasteboard.write([(type: Self.nativeType(for: type), data: data)])
    }

    private static func nativeType(for wire: String) -> String { wire }

    static func containsSensitive(_ types: [String]) -> Bool {
        types.contains { ClipboardWireType.sensitiveTypes.contains($0) }
    }

    static func isPNG(_ data: Data) -> Bool {
        data.starts(with: [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    }
}

// MARK: Real implementations

/// `NSPasteboard.general`.
public struct SystemPasteboard: HelperPasteboard {
    public init() {}
    private var pasteboard: NSPasteboard { .general }

    public var changeCount: Int { pasteboard.changeCount }
    public func availableTypes() -> [String] { (pasteboard.types ?? []).map(\.rawValue) }
    public func data(for type: String) -> Data? { pasteboard.data(forType: NSPasteboard.PasteboardType(type)) }

    public func fileNames() -> [String] {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        return urls.map(\.lastPathComponent)
    }

    public func write(_ items: [(type: String, data: Data)]) -> Int {
        pasteboard.clearContents()
        for item in items { pasteboard.setData(item.data, forType: NSPasteboard.PasteboardType(item.type)) }
        return pasteboard.changeCount
    }
}

/// TIFF to PNG with ImageIO. The size is read from the header first, so a small file cannot expand into a huge bitmap.
public struct ImageIOTranscoder: ImageTranscoder {
    static let maxPixels = 64 * 1024 * 1024

    public init() {}

    public func pngData(fromTIFF data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil), CGImageSourceGetCount(source) > 0,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= Int(LinkLimits.maxPixelDimension), height <= Int(LinkLimits.maxPixelDimension),
              width * height <= Self.maxPixels,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), output.length <= LinkLimits.maxClipboardBytes else { return nil }
        return output as Data
    }
}
