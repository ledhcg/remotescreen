import Foundation
import LinkProtocol

/// The device pasteboard as `LinkClipboardSync` needs it. On iOS, reading content another app copied shows the "allow paste"
/// prompt while reading `changeCount` and the type list does not, so the bridge reads content only when it really sends it.
@MainActor
public protocol LinkPasteboard: AnyObject {
    var changeCount: Int { get }
    /// Type identifiers present (UTIs). Never reads content.
    var typeIdentifiers: [String] { get }
    /// The content for one wire type (`ClipboardWireTypes`); may show the paste prompt. `nil` when it cannot be produced.
    func read(wireType: String) -> Data?
    /// Replaces the pasteboard with `data` of `wireType`.
    func write(wireType: String, data: Data)
    /// Writes text that must stay on this device and expire (Universal Clipboard must not carry it).
    func writeSensitiveText(_ text: String, expiresAfter seconds: TimeInterval)
}

/// Wire type identifiers of `clipboard.*` and the device pasteboard types that carry them. Same names as the helper's
/// `ClipboardWireType`.
public enum ClipboardWireTypes {
    public static let text = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let png = "public.png"

    /// Types this iPad requests from the Mac, best first.
    static let receivable = [text, rtf, html, png]

    /// Pasteboard types that make each wire type available.
    static let nativeTypes: [String: [String]] = [
        text: ["public.utf8-plain-text", "public.plain-text", "public.text"],
        rtf: ["public.rtf"],
        html: ["public.html"],
        png: ["public.png", "public.jpeg", "public.tiff", "public.heic"],
    ]

    /// Markers from nspasteboard.org that password managers attach to content that must not be synced.
    public static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
}

/// Clipboard sync over the App Mode link (`clipboard.offer` / `request` / `data`), one per Mac connection, shared by its windows.
///
/// Rules, the same spirit as `ClipboardBridge` for Screen Sharing:
/// - **Nothing moves unless the person turned sharing on** (`isEnabled`).
/// - **iPad to Mac:** an offer lists the types, never the content. It goes out when a window becomes active and before a paste (⌘V),
///   only if the pasteboard changed since the last offer and the last thing we wrote ourselves. The content is read and sent only for
///   a type we offered, only while the pasteboard is still the one we offered, and never when it carries a concealed/transient marker.
/// - **Mac to iPad:** the Mac's offer is *not* acted on by itself. It is requested right after the person pressed ⌘C or ⌘X in a
///   window (`copyShortcutPressed`), or when a window becomes active. One answer per request; the type, the format and the size are
///   checked before anything is written. Content the Mac marked sensitive is written as local-only text that expires.
@MainActor
public final class LinkClipboardSync {
    /// How long after ⌘C / ⌘X the Mac's next offer is requested at once.
    public static let copyWindow: TimeInterval = 4
    public static let sensitiveLifetime: TimeInterval = 90

    private let pasteboard: any LinkPasteboard
    private let now: () -> TimeInterval
    private let send: (LinkMessage) -> Void
    private let richTypes: Bool

    /// Set by the owner from the person's clipboard mode.
    public var isEnabled: Bool

    private var offeredChangeCount: Int?
    private var offeredTypes: Set<String> = []
    private var syncedChangeCount: Int?
    private var pendingOffer: [String]?
    private var requestedType: String?
    private var requestedSensitive = false
    private var copyUntil: TimeInterval = -.infinity

    /// - Parameters:
    ///   - richTypes: whether the Mac announced `clipboardRich`; without it only text is exchanged.
    public init(
        pasteboard: any LinkPasteboard, isEnabled: Bool, richTypes: Bool,
        now: @escaping () -> TimeInterval = { ProcessInfo.processInfo.systemUptime },
        send: @escaping (LinkMessage) -> Void
    ) {
        self.pasteboard = pasteboard; self.isEnabled = isEnabled; self.richTypes = richTypes; self.now = now; self.send = send
    }

    /// A new connection: nothing offered or requested before it still holds.
    public func reset() {
        offeredChangeCount = nil; offeredTypes = []; pendingOffer = nil; requestedType = nil; copyUntil = -.infinity
    }

    // MARK: Events from the window

    /// A window became active (the scene came forward). Takes up the Mac's latest offer and offers the device's clipboard.
    public func sceneBecameActive() {
        guard isEnabled else { return }
        if let offer = pendingOffer {
            pendingOffer = nil
            request(from: offer)
        }
        _ = offerIfChanged()
    }

    /// ⌘C or ⌘X was pressed for the Mac: its clipboard is about to change, so the next offer is requested at once.
    public func copyShortcutPressed() {
        guard isEnabled else { return }
        copyUntil = now() + Self.copyWindow
    }

    /// ⌘V was pressed. Returns true when an offer was sent, so the caller can hold the key back for a moment while the Mac asks for
    /// and receives the content.
    @discardableResult
    public func pasteShortcutPressed() -> Bool {
        guard isEnabled else { return false }
        return offerIfChanged()
    }

    // MARK: Messages from the Mac

    public func receive(_ message: LinkMessage) {
        guard isEnabled else { return }
        switch message {
        case .clipboardOffer(let types): receiveOffer(types)
        case .clipboardRequest(let type): serve(type: type)
        case .clipboardData(let type, let data): receiveData(type: type, data: data)
        default: break
        }
    }

    // MARK: Device to Mac

    private func wireTypes(of native: [String]) -> [String] {
        let present = Set(native)
        let candidates = richTypes ? ClipboardWireTypes.receivable : [ClipboardWireTypes.text]
        return candidates.filter { wire in ClipboardWireTypes.nativeTypes[wire]?.contains(where: present.contains) == true }
    }

    private func isSensitive(_ native: [String]) -> Bool { native.contains { ClipboardWireTypes.sensitiveTypes.contains($0) } }

    @discardableResult
    private func offerIfChanged() -> Bool {
        let count = pasteboard.changeCount
        guard count != syncedChangeCount, count != offeredChangeCount else { return false }
        let native = pasteboard.typeIdentifiers
        guard !isSensitive(native) else { return false }
        let types = wireTypes(of: native)
        guard !types.isEmpty, types.count <= LinkLimits.maxClipboardTypes else { return false }
        offeredChangeCount = count
        offeredTypes = Set(types)
        send(.clipboardOffer(types: types))
        return true
    }

    private func serve(type: String) {
        guard offeredTypes.contains(type), pasteboard.changeCount == offeredChangeCount,
              !isSensitive(pasteboard.typeIdentifiers) else { return }
        guard let data = pasteboard.read(wireType: type), !data.isEmpty, data.count <= LinkLimits.maxClipboardBytes else { return }
        send(.clipboardData(type: type, data: data))
    }

    // MARK: Mac to device

    private func receiveOffer(_ types: [String]) {
        guard types.count <= LinkLimits.maxClipboardTypes else { return }
        if now() <= copyUntil {
            copyUntil = -.infinity
            request(from: types)
        } else {
            pendingOffer = types
        }
    }

    private func request(from types: [String]) {
        let offered = Set(types)
        let allowed = richTypes ? ClipboardWireTypes.receivable : [ClipboardWireTypes.text]
        guard let choice = allowed.first(where: offered.contains) else { return }
        requestedType = choice
        requestedSensitive = types.contains { ClipboardWireTypes.sensitiveTypes.contains($0) }
        send(.clipboardRequest(type: choice))
    }

    private func receiveData(type: String, data: Data) {
        guard type == requestedType else { return }
        requestedType = nil  // one answer per request
        guard !data.isEmpty, data.count <= LinkLimits.maxClipboardBytes, Self.isWellFormed(data, as: type) else { return }
        if requestedSensitive {
            guard type == ClipboardWireTypes.text, let text = String(data: data, encoding: .utf8) else { return }
            pasteboard.writeSensitiveText(text, expiresAfter: Self.sensitiveLifetime)
        } else {
            pasteboard.write(wireType: type, data: data)
        }
        syncedChangeCount = pasteboard.changeCount  // our own write is not offered back
    }

    /// The content must be what its type says.
    static func isWellFormed(_ data: Data, as type: String) -> Bool {
        switch type {
        case ClipboardWireTypes.text, ClipboardWireTypes.html: String(data: data, encoding: .utf8) != nil
        case ClipboardWireTypes.png: data.starts(with: [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
        case ClipboardWireTypes.rtf: data.starts(with: Data("{\\rtf".utf8))
        default: false
        }
    }
}
