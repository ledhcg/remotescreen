final class FakeOpener: FileOpening, @unchecked Sendable {
    private let lock = NSLock()
    private var _opened: [(URL, String)] = []
    var opened: [(URL, String)] { lock.withLock { _opened } }
    func open(_ file: URL, withApplicationBundleID bundleID: String) async throws { lock.withLock { _opened.append((file, bundleID)) } }
}

private func digest(_ data: Data) -> LinkBytes32 { try! LinkBytes32(Data(SHA256.hash(data: data))) }

final class TestClock: @unchecked Sendable {
    private let lock = NSLock()
    private var current = Date()
    func now() -> Date { lock.withLock { current } }
    func advance(_ seconds: TimeInterval) { lock.withLock { current = current.addingTimeInterval(seconds) } }
}

