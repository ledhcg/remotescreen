final class FakePasteboard: HelperPasteboard, @unchecked Sendable {
    private let lock = NSLock()
    private var _changeCount = 1
    private var contents: [String: Data] = [:]
    private var files: [String] = []
    private(set) var writes: [[(type: String, data: Data)]] = []
    private(set) var dataReads = 0

    var changeCount: Int { lock.withLock { _changeCount } }

    /// A new copy by another app.
    func copy(_ items: [String: Data], files: [String] = []) {
        lock.withLock { contents = items; self.files = files; _changeCount += 1 }
    }

    func availableTypes() -> [String] { lock.withLock { Array(contents.keys).sorted() } }
    func data(for type: String) -> Data? { lock.withLock { dataReads += 1; return contents[type] } }
    func fileNames() -> [String] { lock.withLock { files } }
    func write(_ items: [(type: String, data: Data)]) -> Int {
        lock.withLock {
            writes.append(items)
            contents = Dictionary(uniqueKeysWithValues: items.map { ($0.type, $0.data) })
            _changeCount += 1
            return _changeCount
        }
    }
}

struct FakeTranscoder: ImageTranscoder {
